"""
Script to find bRNA + elements in a .gbk file. Assumes all bRNAs are generated 
from https://github.com/hsulab-arc/BridgeRNADesigner (or the accompanying web 
server)
"""


import argparse
import re
from Bio import SeqIO
from Bio.SeqRecord import SeqRecord
from bridgernadesigner.classes import WTBridgeRNA177nt
from Bio.Seq import reverse_complement


# TODO: allow to find multiple bRNAs!
def find_brna_sequence(record:SeqRecord):
    pattern = re.compile(
        r'AGTGCAGAGAAAATCGGCCAGTTTTCTCTGCCTGCAGTCCGCATGCCGT'
        r'[ACGT]{9}'
        r'TGGGTTCTAACCTGT'
        r'[ACGT]{9}'
        r'TTATGCAGCGGACTGCCTTTCTCCCAAAGTGATAAACCGG'
        r'[ACGT]{8}'
        r'ATGGACCGGTTTTCCCGGTAATCCGT'
        r'[ACGT]{2}TT[ACGT]{7}'
        r'TGGTTTCACT'
    )
    sequence = str(record.seq)
    seq_len = len(sequence)
    BRNA_LENGTH = 177
    L = len(sequence)
    # Allow detection of bRNAs that span the origin
    circular_sequence = sequence + sequence[:BRNA_LENGTH] 
    matches, match_pos, match_strands = [], [], []
    # Search forward strand
    matches_fwd = [match for match in pattern.finditer(circular_sequence)]
    for match in matches_fwd:
        if match and match.start() < seq_len:
            # print(f"Found bRNA on (+) strand: {match.group()}")
            matches.append(match.group())
            match_pos.append(match.start())
            match_strands.append("+")
            # return match.group()

    # Search reverse strand
    rev_sequence = str(record.seq.reverse_complement())
    circular_rev = rev_sequence + rev_sequence[:BRNA_LENGTH]
    matches_rev = [match for match in pattern.finditer(circular_rev)]
    for match in matches_rev:
        if match and match.start() < seq_len:
            # print(f"Found bRNA on (-) strand: {match.group()}")
            matches.append(match.group())
            match_pos.append(L - match.start())
            match_strands.append("-")
            # return match.group()
    if len(matches) == 1:
        brna_seq = matches[0]
        print(f"Found bRNA on ({match_strands[0]}) strand, starting at {match_pos[0]}: {brna_seq}")
        return brna_seq
    elif len(matches) > 1:
        print("Multiple bRNAs found, choose one:")
        for idx, brna in enumerate(zip(matches, match_pos, match_strands)):
            target_site = find_target_site(brna[0], verbose=False)[0]
            donor_site = find_donor_site(brna[0], verbose=False)[0]
            print(f"\t({idx + 1}) ({brna[2]}) strand starting at {brna[1]}; Target site = {target_site}, Donor site = {donor_site} — {brna[0]}")
        BridgeToUse = int(input("Pick integer of one bRNA to use: "))
        brna_seq = matches[BridgeToUse - 1]
        return brna_seq
    else:
        raise ValueError("No bRNA found!")



def find_target_guide(brna_sequence:str):
    ltg = brna_sequence[
        WTBridgeRNA177nt.LTG_REGION[0]:WTBridgeRNA177nt.LTG_REGION[1]
        ]
    rtg = brna_sequence[
        WTBridgeRNA177nt.RTG_REGION[0]:WTBridgeRNA177nt.RTG_REGION[1]
        ]
    return ltg, rtg


def find_donor_guide(brna_sequence:str):
    ldg = brna_sequence[
        WTBridgeRNA177nt.LDG_REGION[0]:WTBridgeRNA177nt.LDG_REGION[1]
        ]
    rdg_1 = brna_sequence[
        WTBridgeRNA177nt.RDG1_REGION[0]:WTBridgeRNA177nt.RDG1_REGION[1]
        ]
    rdg_2 = brna_sequence[
        WTBridgeRNA177nt.RDG2_REGION[0]:WTBridgeRNA177nt.RDG2_REGION[1]
        ]
    return ldg, rdg_1, rdg_2


def find_target_site(brna_sequence, verbose=True):
    ltg, rtg = find_target_guide(brna_sequence)
    # Find target site
    lt = ltg[:-2]
    target_core = ltg[-2:]
    rt = reverse_complement(rtg)[2:]
    target_site = lt + target_core + rt
    if verbose:
        print(f"LTG: {ltg}\nRTG: {rtg}")
        print(f"Target site: {target_site}\n"
            f"    LT: {lt} target core: {target_core} RT: {rt}")
    return target_site, lt, target_core, rt


def find_donor_site(brna_sequence, verbose=True):
    ldg, rdg_1, rdg_2 = find_donor_guide(brna_sequence)
    ld = ldg[:-1]
    core_plus_rdg = (reverse_complement(rdg_1) + reverse_complement(rdg_2))
    donor_core = core_plus_rdg[:2]
    rd = core_plus_rdg[2:]
    donor_site = ld + donor_core + rd
    if verbose:
        print(f"LDG: {ldg}\nRDG1: {rdg_1}\nRDG2: {rdg_2}")
        print(f"Donor site: {donor_site}\n"
            f"    LD: {ld} donor core: {donor_core} RD: {rd}")
    return donor_site, ld, donor_core, rd


def find_target_donor_sites(record:SeqRecord):
    brna_sequence = find_brna_sequence(record)
    target_site, lt, target_core, rt = find_target_site(brna_sequence)
    donor_site, ld, donor_core, rd = find_donor_site(brna_sequence)
    return (target_site, lt, target_core, rt), (donor_site, ld, donor_core, rd)


def main():
    parser = argparse.ArgumentParser(
        description = (
            "Script to predict target and donor sites from a plasmid "
            "containing bRNA generated by https://github.com/hsulab-arc/BridgeRNADesigner")
    )
    parser.add_argument(
        "-b", 
        "--brna_plasmid", 
        help="Path to bRNA plasmid",
        )
    args = parser.parse_args()
    # args.brna_plasmid = "/groups/cress/projects/is110/sequences/SLMQRT/P7YMY9_pSES0099.gbk"
    print(f"Searching {args.brna_plasmid} for bRNA...")
    brna_plasmid_records = SeqIO.parse(args.brna_plasmid, "genbank")
    for brna_plasmid_record in brna_plasmid_records:
        target, donor = find_target_donor_sites(brna_plasmid_record)
        target_site, lt, target_core, rt = target
        donor_site, ld, donor_core, rd = donor
        print(f"{brna_plasmid_record.id}\nFound:\tTarget site: {target_site}\n\tDonor site: {donor_site}")

if __name__ == "__main__":
    main()