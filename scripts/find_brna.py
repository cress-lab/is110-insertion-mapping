def find_brna_sequence(record:SeqRecord):
    pattern = re.compile(
        r'AGTGCAGAGAAAATCGGCCAGTTTTCTCTGCCTGCAGTCCGCATGCCGT'
        r'[ACGT]{9}'
        r'TGGGTTCTAACCTGT'
        r'[ACGT]{9}'
        r'TTATGCAGCGGACTGCCTTTCTCCCAAAGTGATAAACCGG'
        r'[ACGT]{8}'
        r'ATGGACCGGTTTTCCCGGTAATCCGT'
        r'[ACGT]{2}TT[ACGT]{7}'
        r'TGGTTTCACT'
    )
    # search_strand = "+"
    # # print(f"Searching for bRNA on ({search_strand}) strand...")
    # match = pattern.search(str(record.seq))
    # if not match:
    #     search_strand = "-"
    #     # print(f"Searching for bRNA on ({search_strand}) strand...")
    #     match = pattern.search(str(record.seq.reverse_complement()))
    # if match:
    #     brna_seq = str(match.group())
    #     print(f"Found bRNA on ({search_strand}) strand: {brna_seq}")
    #     return brna_seq
    # else:
    #     raise ValueError("No bRNA found!")
    sequence = str(record.seq)
    seq_len = len(sequence)
    circular_sequence = sequence + sequence  # simulate circular genome

    # Search forward strand
    match = pattern.search(circular_sequence)
    if match and match.start() < seq_len:
        print(f"Found bRNA on (+) strand: {match.group()}")
        return match.group()

    # Search reverse strand
    rev_sequence = str(record.seq.reverse_complement())
    circular_rev = rev_sequence + rev_sequence
    match = pattern.search(circular_rev)
    if match and match.start() < seq_len:
        print(f"Found bRNA on (-) strand: {match.group()}")
        return match.group()
    raise ValueError("No bRNA found!")



def find_target_guide(brna_sequence:str):
    ltg = brna_sequence[
        WTBridgeRNA177nt.LTG_REGION[0]:WTBridgeRNA177nt.LTG_REGION[1]
        ]
    rtg = brna_sequence[
        WTBridgeRNA177nt.RTG_REGION[0]:WTBridgeRNA177nt.RTG_REGION[1]
        ]
    return ltg, rtg


def find_donor_guide(brna_sequence:str):
    ldg = brna_sequence[
        WTBridgeRNA177nt.LDG_REGION[0]:WTBridgeRNA177nt.LDG_REGION[1]
        ]
    rdg_1 = brna_sequence[
        WTBridgeRNA177nt.RDG1_REGION[0]:WTBridgeRNA177nt.RDG1_REGION[1]
        ]
    rdg_2 = brna_sequence[
        WTBridgeRNA177nt.RDG2_REGION[0]:WTBridgeRNA177nt.RDG2_REGION[1]
        ]
    return ldg, rdg_1, rdg_2


def find_target_site(brna_sequence):
    ltg, rtg = find_target_guide(brna_sequence)
    print(f"LTG: {ltg}\nRTG: {rtg}")
    # Find target site
    lt = ltg[:-2]
    target_core = ltg[-2:]
    rt = reverse_complement(rtg)[2:]
    target_site = lt + target_core + rt
    print(f"Target site: {target_site}\n"
          f"    LT: {lt} target core: {target_core} RT: {rt}")
    return target_site, lt, target_core, rt


def find_donor_site(brna_sequence):
    ldg, rdg_1, rdg_2 = find_donor_guide(brna_sequence)
    print(f"LDG: {ldg}\nRDG1: {rdg_1}\nRDG2: {rdg_2}")
    ld = ldg[:-1]
    core_plus_rdg = (reverse_complement(rdg_1) + reverse_complement(rdg_2))
    donor_core = core_plus_rdg[:2]
    rd = core_plus_rdg[2:]
    donor_site = ld + donor_core + rd
    print(f"Donor site: {donor_site}\n"
          f"    LD: {ld} donor core: {donor_core} RD: {rd}")
    return donor_site, ld, donor_core, rd


def find_target_donor_sites(record:SeqRecord):
    brna_sequence = find_brna_sequence(record)
    target_site, lt, target_core, rt = find_target_site(brna_sequence)
    donor_site, ld, donor_core, rd = find_donor_site(brna_sequence)
    return (target_site, lt, target_core, rt), (donor_site, ld, donor_core, rd)


